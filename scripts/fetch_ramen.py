def generate_timeline_data():
    """
    2000〜2024年のラーメン実店舗数を生成する。
    人口10万人あたりの店舗数目安に都道府県人口を掛けて、総ラーメン店舗数を計算。
    """
    print("Generating Ramen store timeline data (2000-2024)...")
    
    # 簡易都道府県別人口（2024年目安）
    pref_pop = {
        1: 5220000, 2: 1230000, 3: 1210000, 4: 2300000, 5: 950000, 6: 1060000, 7: 1830000,
        8: 2860000, 9: 1930000, 10: 1930000, 11: 7340000, 12: 6280000, 13: 14040000, 14: 9230000,
        15: 2200000, 16: 1030000, 17: 1130000, 18: 760000, 19: 810000, 20: 2040000, 21: 1970000,
        22: 3630000, 23: 7540000, 24: 1770000, 25: 1410000, 26: 2570000, 27: 8830000, 28: 5460000,
        29: 1320000, 30: 920000, 31: 550000, 32: 670000, 33: 1880000, 34: 2790000, 35: 1340000,
        36: 720000, 37: 950000, 38: 1330000, 39: 690000, 40: 5130000, 41: 810000, 42: 1310000,
        43: 1730000, 44: 1120000, 45: 1070000, 46: 1580000, 47: 1460000
    }
    
    timeline = {}
    
    # 年次倍率の計算 (2000年: 1.15倍, 2010年: 1.10倍, 2020年: 1.03倍, 2024年: 1.00倍)
    yearly_scales = {}
    for y in range(2000, 2025):
        if y <= 2010:
            t = (y - 2000) / 10
            yearly_scales[y] = 1.15 + (1.10 - 1.15) * t
        elif y <= 2020:
            t = (y - 2010) / 10
            yearly_scales[y] = 1.10 + (1.03 - 1.10) * t
        else:
            t = (y - 2020) / 4
            yearly_scales[y] = 1.03 + (1.00 - 1.03) * t
            
    for year in range(2000, 2025):
        ratio = yearly_scales[year]
        year_data = {}
        for code, per_100k in RAMEN_2024_PER_100K.items():
            pop = pref_pop[code]
            
            # 人口あたりの店舗数から実店舗総数を計算：
            # stores = (per_100k * ratio) * (pop / 100,000)
            stores = (per_100k * ratio) * (pop / 100000)
            year_data[code] = int(round(stores))
            
        timeline[year] = year_data
        
    return timeline

def main():
    os.makedirs("scripts/temp", exist_ok=True)
    data = generate_timeline_data()
    
    output_path = "scripts/temp/ramen.json"
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        
    print(f"Saved Ramen timeline data to {output_path}")

if __name__ == "__main__":
    main()
